import { IsString, IsNotEmpty, IsOptional, IsUUID } from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class EmbedChatDto {
  @ApiProperty({
    description: 'Signed embed token generated by API key secret',
  })
  @IsNotEmpty()
  @IsString()
  token: string;

  @ApiProperty({
    description: 'Message to send to the assistant',
    example: 'Hi, what are your store hours?',
  })
  @IsNotEmpty()
  @IsString()
  message: string;

  @ApiPropertyOptional({
    description: 'Optional conversation ID to maintain continuous session thread',
  })
  @IsOptional()
  @IsUUID('4')
  conversationId?: string;
}
